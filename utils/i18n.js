function t(key, lang) {
  lang = lang || 'th';
  const langDict = translations[lang] || translations.th;
  return langDict[key] || translations.th[key] || key;
}

function adminLocaleMiddleware(req, res, next) {
  let lang = 'th';
  if (req.cookies && req.cookies.admin_lang) {
    lang = req.cookies.admin_lang === 'en' ? 'en' : 'th';
  }
  res.locals.adminLang = lang;
  res.locals.t = (key) => t(key, lang);
  next();
}

module.exports = { translations, t, adminLocaleMiddleware };
